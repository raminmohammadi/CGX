def _norm(p: str) -> str:
    return (p or "").replace("\\", "/").strip("/")


def ui_files_to_inject(brief: Any, paths: Iterable[str]) -> List[Dict[str, Any]]:
    """Canonical UI files the plan lacks, as ``{path, description, depends_on}``.

    Only files CGX can describe precisely (and in the tokens file's case,
    generate itself) are injected; screens/components stay the planner's job.
    """
    b = _brief(brief)
    if not b.applies:
        return []
    have = {_norm(p) for p in paths}
    bases = {p.rsplit("/", 1)[-1].lower() for p in have}
    out: List[Dict[str, Any]] = []

    def add(path: str, desc: str, deps: Optional[List[str]] = None) -> None:
        if path and _norm(path) not in have:
            out.append({"path": path, "description": desc, "depends_on": list(deps or [])})

    r = b.ui_dir()
    add(b.tokens_path, "Design tokens + base styles (generated by CGX from the selected theme: :root CSS "
                       "variables, element defaults, focus rings, base component classes, responsive rules).")
    if b.global_css_path:
        add(b.global_css_path, f"App-specific layout and component styles for {b.product_name} ({b.archetype_name}) "
                                "built on the tokens stylesheet's variables and classes; hover/focus/disabled states and "
                                "a mobile @media block.", [b.tokens_path])
    if b.framework in ("react", "vue"):
        add(b.html_path, "Vite HTML entry: viewport meta, title, root element, module script for the entry file.")
        if not any(bs == "package.json" and (not r or p.startswith(r)) for p, bs in ((p, p.rsplit('/', 1)[-1].lower()) for p in have)):
            add(f"{r}package.json", "Node manifest for the frontend: framework + router + vite + vitest dependencies "
                                    "and dev/build/preview/test scripts.")
        vite_cfg = f"{r}vite.config.{'ts' if b.typescript else 'js'}"
        if not any(bs.startswith("vite.config") for bs in bases):
            add(vite_cfg, "Vite config with the framework plugin (and vitest jsdom environment).")
        add(b.entry_path, "Entry module: imports the stylesheets, mounts the app shell (createRoot / createApp) "
                          "with StrictMode and the router when the app has multiple screens.")
        add(b.app_path, "App shell: header/top bar with brand + navigation, routed screens inside <main>; loads "
                        "persisted settings on mount.", [b.entry_path] if False else [])
    elif b.framework == "html":
        add(b.html_path, "Home page: semantic header/nav/main/footer, viewport meta, links css/tokens.css then "
                         "css/styles.css, loads js/app.js (defer).")
        add(b.entry_path, "Page behaviour as a plain ES module (nav toggle, forms with validation + persistence).")
    elif b.framework == "nextjs":
        add(b.entry_path, "Root layout: imports globals.css, renders the app shell (header/nav) around {children}.")
        add(b.app_path, "Home page route.")
    if b.external_api:
        add(b.api_client_path, "API client -- the only module that calls fetch: reads the configured base URL and "
                                "key from the storage helper, sends JSON with Authorization: Bearer, normalises "
                                "HTTP/network errors into readable messages, exports the request functions screens use.",
            [b.storage_path] if b.persistence else [])
    if b.persistence:
        add(b.storage_path, "Storage helper over localStorage: load/save/clear settings and app data with safe JSON "
                             "parsing and defaults; namespaced keys; seeds the sample data on first run when a "
                             "sample-data module exists.", [b.sample_data_path] if b.sample_data_path else [])
    if b.sample_data_path:
        add(b.sample_data_path, f"Realistic seed data for {b.product_name}: 12-30 records with real-looking names, "
                                 "4-8 categories, ISO dates over the last 90 days and plausible amounts, exported as "
                                 "arrays plus small aggregation helpers (totals by category / by month).")
    return out


def plan_problems(brief: Any, paths: Iterable[str]) -> List[str]:
    """Fatal, non-injectable plan problems for a UI brief (empty = fine)."""
    b = _brief(brief)
    if not b.applies:
        return []
    ps = [_norm(p) for p in paths]
    problems: List[str] = []
    ui_sources = [p for p in ps if p.endswith(UI_SOURCE_EXT)
                  or (b.framework == "html" and p.endswith(".html"))]
    if not ui_sources:
        problems.append(f"the plan has no UI source files for a {b.archetype_name} ({b.framework}); plan one file "
                        "per screen (e.g. src/pages/<Screen>." + ("vue" if b.framework == "vue" else "jsx") + ") "
                        "plus the app shell")
    elif b.framework != "html":
        screens_needed = max(1, len(b.screens))
        non_shell = [p for p in ui_sources if p != _norm(b.app_path)]
        if b.multi_screen and len(non_shell) < min(2, screens_needed):
            problems.append(f"the plan has only {len(non_shell)} screen/component file(s) for screens "
                            f"{b.screens}; add one component file per screen")
    return problems


