_HEX_RE = re.compile(r"(?<![\w&])#(?:[0-9a-fA-F]{3}){1,2}\b")
_JSX_TAG_RE = re.compile(r"<(div|main|section|header|nav|form|ul|button|input|textarea|aside|footer|article)\b")
_CLASS_RE = re.compile(r"\b(className|class)\s*=")
_STYLE_IMPORT_RE = re.compile(r"""import\s+['"][^'"]+\.(?:css|scss|sass|less)['"]""")
_HTML_LINK_CSS_RE = re.compile(r"""<link[^>]+rel\s*=\s*['"]stylesheet['"][^>]*>""", re.I)
_VIEWPORT_RE = re.compile(r"""<meta[^>]+name\s*=\s*['"]viewport['"]""", re.I)
_REACTDOM_RENDER_RE = re.compile(r"\bReactDOM\.render\s*\(|\brender\s*\(\s*<[^)]*,\s*document\.getElementById")
_HARDCODED_API_RE = re.compile(r"""(?:fetch|axios\.(?:get|post|put|delete|patch))\s*\(\s*[`'"]/api/""")
_STORAGE_RE = re.compile(r"\b(localStorage|sessionStorage|indexedDB)\b")
_ROUTER_RE = re.compile(r"""from\s+['"](react-router(?:-dom)?|vue-router|next/navigation|next/link|@tanstack/react-router)['"]""")
_NAV_RE = re.compile(r"<nav\b|role\s*=\s*['\"]tablist['\"]|\.nav-link|aria-current", re.I)
_INPUT_RE = re.compile(r"<(input|textarea|select)\b([^>]*)>", re.I)
_LABEL_RE = re.compile(r"<label\b", re.I)
_FETCH_RE = re.compile(r"\bfetch\s*\(|\baxios\b")
_ASYNC_STATE_RE = re.compile(r"\b(loading|isLoading|pending|isPending|busy|sending|error|setError|catch\s*\()", re.I)
_MAP_RE = re.compile(r"\.map\s*\(")
_EMPTY_RE = re.compile(r"length\s*===?\s*0|\.length\s*\?|!\w+\.length|length\s*<\s*1|empty-state|EmptyState|No\s+\w+\s+yet", re.I)
_MEDIA_RE = re.compile(r"@media")
_ALERT_RE = re.compile(r"\balert\s*\(")
_CONSOLE_RE = re.compile(r"console\.log\s*\(")
_FORM_RE = re.compile(r"<form\b|onSubmit", re.I)
_EFFECT_RE = re.compile(r"\b(localStorage|sessionStorage|fetch\s*\(|axios|navigate\s*\(|setItem|saveSettings|save\w*\(|dispatch\(|onSave|props\.on[A-Z]\w*\(|emit\(|router\.push|useNavigate)\b")
_PLACEHOLDER_COPY_RE = re.compile(r"lorem ipsum|TODO|FIXME|placeholder text|Click here", re.I)
_SECRET_LOG_RE = re.compile(r"console\.(?:log|info|debug|warn|error)\([^)]*\b(?:apiKey|api_key|apiToken|token|secret|password|accessToken)\b", re.I)
_LINK_TO_RE = re.compile(r"""<(?:Nav)?Link\b[^>]*\bto\s*=\s*['"](/[^'"#?]*)['"]""")
_ROUTE_PATH_RE = re.compile(r"""<Route\b[^>]*\bpath\s*=\s*['"]([^'"]+)['"]""")
_TOKENS_VAR_RE = re.compile(r"var\(--")


def _ui_source(brief: DesignBrief, path: str, kind: str) -> bool:
    low = path.lower()
    return kind in ("component", "app", "entry") and (low.endswith(UI_SOURCE_EXT) or low.endswith((".js", ".ts")))


def check_tree(brief: Any, files: Dict[str, str]) -> List[DesignIssue]:
    """Run every deterministic UI check over ``{path: content}``. Never raises."""
    b = _brief(brief)
    if not b.applies:
        return []
    try:
        return _check_tree(b, {_norm(p): (c or "") for p, c in (files or {}).items()})
    except Exception:  # pragma: no cover - checks are best-effort
        return []


def _check_tree(b: DesignBrief, files: Dict[str, str]) -> List[DesignIssue]:
    issues: List[DesignIssue] = []
    kinds = {p: file_kind(b, p) for p in files}
    stylesheets = [p for p, k in kinds.items() if k in ("stylesheet", "tokens")]
    ui_sources = [p for p, k in kinds.items() if _ui_source(b, p, k)]
    components = [p for p, k in kinds.items() if k == "component" and p.lower().endswith(UI_SOURCE_EXT)]
    html_files = [p for p, k in kinds.items() if k == "html"]
    entry = files.get(_norm(b.entry_path), "")
    app = files.get(_norm(b.app_path), "")
    all_text = "\n".join(files.values())
    ui_text = "\n".join(files[p] for p in ui_sources) + "\n" + "\n".join(files[p] for p in html_files)

    # D01 -- a stylesheet must exist (tailwind: the entry css with @import "tailwindcss").
    if not stylesheets:
        target = b.tokens_path or (b.ui_dir() + "src/styles/tokens.css")
        issues.append(DesignIssue(
            "D01-no-stylesheet", "fatal", target,
            "no stylesheet in the tree -- the UI renders unstyled",
            directive="Create the design tokens stylesheet (CSS variables for colours, type, spacing, radius, "
                      "shadows; base element styles; .btn/.card/.input/.topbar classes) and import it from the entry.",
            regen_file=target))
    # D02 -- the tokens/global stylesheet must be imported (entry) or linked (html).
    if stylesheets and b.framework in ("react", "vue", "nextjs"):
        imported = bool(_STYLE_IMPORT_RE.search(entry)) or bool(_STYLE_IMPORT_RE.search(app)) or \
            any(_STYLE_IMPORT_RE.search(files[p]) for p in ui_sources)
        if not imported and entry:
            issues.append(DesignIssue(
                "D02-stylesheet-not-imported", "fatal", _norm(b.entry_path),
                "no component or the entry imports a stylesheet -- the design tokens never load",
                directive=f"Import the stylesheets at the top of the entry module: import './{_rel(b.entry_path, b.tokens_path)}'"
                          + (f"; import './{_rel(b.entry_path, b.global_css_path)}'" if b.global_css_path else "") + ".",
                regen_file=_norm(b.entry_path)))
    if b.framework == "html":
        # Only full documents (with a <head>) must link styles / declare the
        # viewport; partials and child templates inherit from their base.
        for p in [h for h in html_files if "<head" in files[h].lower()]:
            if not _HTML_LINK_CSS_RE.search(files[p]):
                issues.append(DesignIssue(
                    "D02-stylesheet-not-linked", "fatal", p,
                    f"{p} links no stylesheet",
                    directive="Add <link rel=\"stylesheet\" href=\"css/tokens.css\"> and <link rel=\"stylesheet\" "
                              "href=\"css/styles.css\"> in <head>."))
    # D03 -- unstyled component: JSX/markup with zero className/class.
    for p in components + ([_norm(b.app_path)] if app and b.framework != "html" else []):
        txt = files.get(p, "")
        if not txt:
            continue
        tags = len(_JSX_TAG_RE.findall(txt))
        if tags >= 2 and not _CLASS_RE.search(txt) and "styled." not in txt and "css`" not in txt:
            issues.append(DesignIssue(
                "D03-unstyled-component", "fatal", p,
                f"{p} renders {tags} elements with no className -- it is unstyled",
                directive="Give every element group a className from the tokens stylesheet (.page-header, .card, "
                          ".field/.label/.input, .btn.btn-primary, .empty-state, .alert) and a descriptive root class; "
                          "structure it as a real screen with title, states and feedback."))
    # D04 -- multi-screen needs a router or an explicit nav.
    if b.multi_screen and b.framework in ("react", "vue") and ui_sources:
        if not _ROUTER_RE.search(ui_text) and not _NAV_RE.search(ui_text):
            issues.append(DesignIssue(
                "D04-no-navigation", "fatal", _norm(b.app_path) or ui_sources[0],
                "multi-screen app has neither a router nor a <nav> -- users cannot move between screens",
                directive="Add navigation: a <header class=\"topbar\"> with a <nav class=\"nav\"> of NavLink/RouterLink "
                          "items (active class) and route each screen (react-router <Routes>/<Route>), or an "
                          "explicit tab bar with aria-current on the active tab.",
                regen_file=_norm(b.app_path) or ui_sources[0]))
    # D05 -- viewport meta (full documents only).
    for p in [h for h in html_files if "<head" in files[h].lower()]:
        if not _VIEWPORT_RE.search(files[p]):
            issues.append(DesignIssue(
                "D05-no-viewport", "fatal", p, f"{p} has no viewport meta -- broken on mobile",
                directive='Add <meta name="viewport" content="width=device-width, initial-scale=1.0"> in <head>.'))
    # D06 -- ReactDOM.render on React 19 renders nothing.
    if b.framework == "react":
        for p in ui_sources:
            if _REACTDOM_RENDER_RE.search(files[p]) and "createRoot" not in files[p]:
                issues.append(DesignIssue(
                    "D06-legacy-render", "fatal", p,
                    f"{p} uses ReactDOM.render, which is removed in React 19 (blank page)",
                    directive="Use import { createRoot } from 'react-dom/client'; "
                              "createRoot(document.getElementById('root')).render(<StrictMode><App/></StrictMode>)."))
    # D07 -- hard-coded /api URL when the user configures the endpoint.
    if b.external_api:
        for p, txt in files.items():
            if kinds[p] in ("component", "app", "api", "script", "entry", "storage") and _HARDCODED_API_RE.search(txt):
                issues.append(DesignIssue(
                    "D07-hardcoded-api", "fatal", p,
                    f"{p} calls a hard-coded '/api/...' URL although the user configures the API address",
                    directive="Build request URLs from the saved settings' base URL (storage helper) and send "
                              "'Authorization: Bearer <key>'; keep all fetch calls in the API client module."))
    # D08 -- persistence required but nothing stores anything.
    if b.persistence and ui_sources and not _STORAGE_RE.search(all_text):
        target = _norm(b.storage_path) if _norm(b.storage_path) in files else (
            next((p for p in ui_sources if "setting" in p.lower() or "profile" in p.lower()), ui_sources[0]))
        issues.append(DesignIssue(
            "D08-no-persistence", "fatal", target,
            "nothing persists settings/data (no localStorage/sessionStorage/indexedDB) -- state is lost on reload",
            directive="Persist settings and user data with localStorage (JSON, namespaced keys, safe parsing) and "
                      "load them on start.", regen_file=target))
    # D18 -- a secret written to the console.
    for p, txt in files.items():
        if kinds[p] in ("component", "app", "api", "storage", "script", "entry") and _SECRET_LOG_RE.search(txt):
            issues.append(DesignIssue(
                "D18-secret-logged", "fatal", p,
                f"{p} logs a credential (API key/token/password) to the console",
                directive="Never log secrets: remove the console statement or log a masked value (e.g. the last 4 chars)."))
    # D17 -- a placeholder component: a default-exported component whose JSX has
    # no text, no child elements and no expressions (`<div>{/* TODO */}</div>`).
    # The no-stub gate for Python's contract functions, applied to UI pieces.
    for p in components:
        txt = files[p]
        if _is_stub_component(txt):
            issues.append(DesignIssue(
                "D17-stub-component", "fatal", p,
                f"{p} is a placeholder component that renders nothing",
                directive="Implement this component for real per its description: semantic markup with "
                          "tokens classes, the props its callers pass, and real copy -- no placeholder "
                          "comments or empty wrappers."))
    # D09 -- console.log-only form handler.
    for p in components:
        txt = files[p]
        if _FORM_RE.search(txt) and _CONSOLE_RE.search(txt) and not _EFFECT_RE.search(txt):
            issues.append(DesignIssue(
                "D09-log-only-handler", "fatal", p,
                f"{p} has a form whose submit handler only console.logs -- nothing is saved or sent",
                directive="Make the submit handler persist the values (storage helper) and/or call the API client, "
                          "then show inline success/error feedback; remove console.log."))
    # ---- warnings ---------------------------------------------------------
    for p in components:
        txt = files[p]
        hexes = _HEX_RE.findall(txt)
        if len(hexes) > 3 and _TOKENS_VAR_RE.search("\n".join(files[s] for s in stylesheets)):
            issues.append(DesignIssue(
                "D10-hardcoded-colors", "warning", p,
                f"{p} hard-codes {len(hexes)} hex colours instead of design tokens",
                directive="Replace hard-coded colours with var(--color-*) tokens or the shared classes."))
        for m in _INPUT_RE.finditer(txt):
            attrs = m.group(2)
            if "type=\"hidden\"" in attrs or "type='hidden'" in attrs:
                continue
            if "aria-label" not in attrs and "id=" not in attrs and not _LABEL_RE.search(txt):
                issues.append(DesignIssue(
                    "D11-unlabelled-input", "warning", p,
                    f"{p} has an input without a <label>/aria-label",
                    directive="Wrap each input in a .field with a <label htmlFor> (or add aria-label for icon/search inputs)."))
                break
        if _FETCH_RE.search(txt) and not _ASYNC_STATE_RE.search(txt):
            issues.append(DesignIssue(
                "D12-no-async-states", "warning", p,
                f"{p} performs requests without loading/error state handling",
                directive="Track loading and error state around the request and render a spinner / .alert--error with Retry."))
        if _MAP_RE.search(txt) and not _EMPTY_RE.search(txt):
            issues.append(DesignIssue(
                "D13-no-empty-state", "warning", p,
                f"{p} renders a list without an empty state",
                directive="Render a .empty-state (headline + hint + action) when the list has no items."))
        if _ALERT_RE.search(txt):
            issues.append(DesignIssue(
                "D14-alert-usage", "warning", p, f"{p} uses alert() for feedback",
                directive="Replace alert() with inline feedback (.alert / toast) in the UI."))
        if _PLACEHOLDER_COPY_RE.search(txt):
            issues.append(DesignIssue(
                "D15-placeholder-copy", "warning", p, f"{p} contains placeholder copy (lorem ipsum / TODO / 'Click here')",
                directive="Replace placeholder copy with real, product-specific text."))
    # D20 -- a Link/NavLink pointing at a path no <Route> declares (dead navigation).
    all_routes = {r for p in ui_sources for r in _ROUTE_PATH_RE.findall(files[p])}
    if all_routes:
        for p in ui_sources:
            dead = sorted({t for t in _LINK_TO_RE.findall(files[p])
                           if t not in all_routes and t.rstrip("/") not in all_routes and "*" not in all_routes
                           and not any(r.endswith("/*") and t.startswith(r[:-1]) for r in all_routes)})
            if dead:
                issues.append(DesignIssue(
                    "D20-dead-link", "warning", p,
                    f"{p} links to {', '.join(dead)} but no <Route> declares that path",
                    directive=f"Point the link(s) at a declared route ({', '.join(sorted(all_routes))}) or add the route."))
    if b.styling != "tailwind" and stylesheets:
        app_css = files.get(_norm(b.global_css_path), "") if b.global_css_path else ""
        if app_css and not _MEDIA_RE.search(app_css):
            issues.append(DesignIssue(
                "D16-not-responsive", "warning", _norm(b.global_css_path),
                "the app stylesheet has no @media rules",
                directive="Add a @media (max-width: 768px) block that stacks layouts and tightens padding."))
    return issues


_JSX_RETURN_PAREN_RE = re.compile(r"return\s*\(\s*([\s\S]*?)\s*\)\s*;", re.S)
_JSX_RETURN_BARE_RE = re.compile(r"return\s+(<[\s\S]*?);\s*\}", re.S)


def _is_stub_component(txt: str) -> bool:
    """True when the component's JSX is one bare element with no text, child,
    expression or attribute beyond ``className`` (``<div>{/* TODO */}</div>``)."""
    body = re.sub(r"\{/\*.*?\*/\}", "", txt or "", flags=re.S)  # strip JSX comments
    m = _JSX_RETURN_PAREN_RE.search(body) or _JSX_RETURN_BARE_RE.search(body)
    if not m:
        return False
    jsx = m.group(1).strip()
    if not jsx.startswith("<"):
        return False
    open_tags = re.findall(r"<([A-Za-z][\w.-]*)([^>]*)>", jsx)
    if len(open_tags) != 1:
        return False
    attrs = re.sub(r"\b(className|class)\s*=\s*(\"[^\"]*\"|'[^']*'|\{[^}]*\})", "", open_tags[0][1])
    if re.search(r"[A-Za-z-]+\s*=", attrs) or "{..." in attrs:
        return False  # aria-label / role / props -> intentional leaf (icon, spinner)
    text = re.sub(r"<[^>]+>", "", jsx)
    text = re.sub(r"\{[^}]*\}", lambda mm: "x" if mm.group(0).strip("{} ") else "", text)
    return not text.strip()


def _rel(from_path: str, to_path: str) -> str:
    """Relative import specifier from ``from_path``'s directory to ``to_path``."""
    import posixpath
    f_dir = posixpath.dirname(_norm(from_path))
    rel = posixpath.relpath(_norm(to_path), f_dir or ".")
    return rel if rel.startswith(".") else rel


def fatal_issues(issues: Iterable[DesignIssue]) -> List[DesignIssue]:
    return [i for i in issues if i.severity == "fatal"]


def issues_as_warnings(issues: Iterable[DesignIssue]) -> List[Dict[str, Any]]:
    """Serialise issues in the verifier's ``import_warnings`` row shape."""
    out: List[Dict[str, Any]] = []
    for i in issues:
        out.append({"file": i.file, "define_in": i.regen_file or i.file,
                    "directive": i.directive, "reason": i.message,
                    "kind": "design", "severity": i.severity, "id": i.id})
    return out
