"""Deterministic UI-quality checks + plan-level UI invariants.

The Verifier previously judged a frontend only by "does it parse / build" --
so a white page with two unstyled buttons shipped as *verified*. These checks
read the generated FILE TEXT (no browser needed) and flag the defects that make
an app visibly broken or that violate the brief:

* FATAL (gates verify + drives a targeted regenerate with a directive): no
  stylesheet, stylesheet never imported, an unstyled component (JSX with zero
  ``className``), ``ReactDOM.render`` on React 19 (blank page), a hard-coded
  ``/api/...`` URL when the user configures the endpoint, no persistence when
  the brief requires it, a multi-screen app with neither router nor nav, a
  missing viewport meta, a form handler whose only effect is ``console.log``.
* WARNING (advisory, reported + handed to the critic): hard-coded hex colours,
  inputs without labels, fetch without loading/error handling, lists without
  an empty state, missing responsive rules, ``alert()`` usage.

Plan-level helpers make the design system a *guarantee*: :func:`ui_files_to_inject`
lists the canonical UI files a plan is missing (tokens stylesheet, app
stylesheet, entry, shell, API client, storage helper) so the Tech Lead injects
them deterministically, and :func:`plan_problems` names the few things that
cannot be injected (e.g. a UI brief with no screen components at all).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, Iterable, List, Optional

from cgx.design.brief import DesignBrief
from cgx.design.prompts import UI_SOURCE_EXT, file_kind
from cgx.design.themes import tailwind_entry_stylesheet, theme_by_key, tokens_stylesheet

__all__ = ["DesignIssue", "check_tree", "plan_problems", "ui_files_to_inject", "tokens_content",
           "is_tokens_path", "fatal_issues", "issues_as_warnings"]


@dataclass
class DesignIssue:
    id: str
    severity: str          # "fatal" | "warning"
    file: str
    message: str
    directive: str = ""    # additive fix instruction for the regen prompt
    regen_file: str = ""   # file to regenerate (defaults to ``file``)
    extra: Dict[str, Any] = field(default_factory=dict)

    def as_dict(self) -> Dict[str, Any]:
        return {"id": self.id, "severity": self.severity, "file": self.file,
                "message": self.message, "directive": self.directive,
                "regen_file": self.regen_file or self.file}


def _brief(b: Any) -> DesignBrief:
    return b if isinstance(b, DesignBrief) else DesignBrief.from_dict(b)


def is_tokens_path(brief: Any, path: str) -> bool:
    b = _brief(brief)
    return bool(b.applies and b.tokens_path and
                (path or "").replace("\\", "/") == b.tokens_path)


def tokens_content(brief: Any) -> str:
    """The deterministic tokens stylesheet for the brief's theme/styling."""
    b = _brief(brief)
    theme = theme_by_key(b.theme) or theme_by_key("clean-tech")
    if b.styling == "tailwind":
        return tailwind_entry_stylesheet(theme)
    return tokens_stylesheet(theme, app_name=b.product_name)


